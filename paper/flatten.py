"""Write one self-contained main.tex for a paper: every \\input inlined.

    python paper/flatten.py journal                       # Springer (sn-jnl)
    python paper/flatten.py conference                    # IEEE conference
    python paper/flatten.py journal --wrapper generic     # any file in wrappers/
    python paper/flatten.py conference --check            # fail if main.tex is stale

The paper's sources stay where they are (content/, meta.tex, wrappers/); main.tex is
generated from them, so the whole paper (preamble, title, authors, sections, tables,
declarations, appendix) is in one file for Overleaf. refs.bib, figures/ and the class
files stay separate, as LaTeX needs them. The anonymous switch is kept: uncomment
\\def\\anonymousbuild{} at the top of main.tex for a double-blind build.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DEFAULT = {"journal": "springer-sn-jnl", "conference": "ieeetran-conf"}
INPUT = re.compile(r"\\input\{([^}]+)\}")
HEADER = """%% {title}
%%
%% GENERATED by paper/flatten.py from content/, meta.tex and wrappers/{wrapper}.tex:
%% the whole paper in one file. Edit the sources and run
%%   python paper/flatten.py {paper}{wrapper_arg}
%% or edit this file directly if you work only in Overleaf (then it is the source).
%%
%% Double-blind build: uncomment the next line.
%\\def\\anonymousbuild{{}}
%% Drop the appendix (if the paper has one): uncomment the next line.
%\\def\\noappendix{{}}
"""


def expand(text: str, folder: Path, seen: tuple[str, ...] = ()) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("%"):
            out.append(line)
            continue

        def inline(m: re.Match[str]) -> str:
            name = m.group(1)
            path = folder / (name if name.endswith(".tex") else name + ".tex")
            if name in seen:
                raise SystemExit(f"\\input cycle at {name}")
            body = expand(path.read_text(encoding="utf-8"), folder, (*seen, name))
            return f"%% ---- begin {name} ----\n{body.rstrip()}\n%% ---- end {name} ----\n"

        out.append(INPUT.sub(inline, line))
    return "".join(out)


def build(paper: str, wrapper: str) -> str:
    folder = ROOT / paper
    title = re.search(r"\\newcommand\{\\ssTitle\}\{(.*)\}", (folder / "meta.tex").read_text())
    body = expand((folder / "wrappers" / f"{wrapper}.tex").read_text(encoding="utf-8"), folder)
    arg = "" if wrapper == DEFAULT[paper] else f" --wrapper {wrapper}"
    head = HEADER.format(
        title=title.group(1) if title else paper, wrapper=wrapper, paper=paper, wrapper_arg=arg
    )
    return head + body


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("paper", choices=sorted(DEFAULT))
    ap.add_argument("--wrapper", help="file in wrappers/ (default: the paper's default)")
    ap.add_argument("--check", action="store_true", help="exit 1 if main.tex is out of date")
    args = ap.parse_args()
    target = ROOT / args.paper / "main.tex"
    text = build(args.paper, args.wrapper or DEFAULT[args.paper])
    if args.check:
        stale = not target.exists() or target.read_text(encoding="utf-8") != text
        print(f"{target}: {'out of date' if stale else 'up to date'}")
        sys.exit(1 if stale else 0)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
