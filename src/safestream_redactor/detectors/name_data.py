"""Lexical resources for the gazetteer/context name detector.

These lists are **general-purpose** English-language resources — common honorifics,
professional suffixes, corporate designators, form-field cue words, and a modest
set of common given names. They are deliberately source-agnostic (drawn from
everyday English usage, NOT from any evaluation corpus) so the detector
generalizes; nothing here is tuned to a particular benchmark.

The given-name gazetteer is intentionally small and high-frequency. It is used
only as a *weak* signal (a low-confidence candidate that a following capitalized
token turns into a person name), because a large gazetteer trades precision for
recall on ordinary prose (many given names are also common words: "April",
"Mark", "Grace", "Will"). Callers who need broader coverage should supply the
NER/ONNX tier instead.
"""

