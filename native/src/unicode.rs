//! Python-exact character classes, and the "shadow" text that makes the `regex`
//! crate see them.
//!
//! Python's `re` and Rust's `regex` disagree on Unicode classes:
//!
//! * `\w` — Python is `c.isalnum() or c == "_"` (includes No numerics like `²`,
//!   excludes combining marks and connector punctuation other than `_`); Rust
//!   uses UTS#18 (Alphabetic ∪ M ∪ Nd ∪ Pc ∪ Join_Control). `\b` inherits this.
//! * `\s` — Python is `c.isspace()`, which includes `\x1c`–`\x1f`; Rust uses
//!   White_Space, which does not.
//! * `\d` — both are Nd, but each pins its own Unicode version.
//!
//! The predicates here are Python's, from tables generated by asking Python's
//! `re` about every codepoint (`native/scripts/gen_unicode_tables.py`) and
//! re-checked codepoint by codepoint by `tests/test_native_backend.py`.

use crate::unicode_tables::{PY_SPACE, PY_WORD};
use std::borrow::Cow;

// --- Unicode decimal-digit value (Python int() parity) -----------------------
//
// Python's int() accepts ANY Unicode decimal digit (category Nd), so it detects
// Unicode-digit IPv4 like `٩٩.٩.٩.٩`. Rust's str::parse/char::to_digit are
// ASCII-only, so IPv4's octet-range validator would under-detect without this.
//
// Every Nd character is one of 76 contiguous 10-codepoint blocks (Unicode 16.0,
// the version of Python 3.14): its value is `codepoint - block_zero`.
// DIGIT_BLOCK_ZEROS lists each block's '0'. A Python-side test verifies, for
// EVERY codepoint, that native digit value == Python int() on Nd characters and
// that the set of digits is exactly Python's `\d`.
const DIGIT_BLOCK_ZEROS: &[u32] = &[
    0x30, 0x660, 0x6F0, 0x7C0, 0x966, 0x9E6, 0xA66, 0xAE6, 0xB66, 0xBE6, 0xC66, 0xCE6, 0xD66,
    0xDE6, 0xE50, 0xED0, 0xF20, 0x1040, 0x1090, 0x17E0, 0x1810, 0x1946, 0x19D0, 0x1A80, 0x1A90,
    0x1B50, 0x1BB0, 0x1C40, 0x1C50, 0xA620, 0xA8D0, 0xA900, 0xA9D0, 0xA9F0, 0xAA50, 0xABF0, 0xFF10,
    0x104A0, 0x10D30, 0x10D40, 0x11066, 0x110F0, 0x11136, 0x111D0, 0x112F0, 0x11450, 0x114D0,
    0x11650, 0x116C0, 0x116D0, 0x116DA, 0x11730, 0x118E0, 0x11950, 0x11BF0, 0x11C50, 0x11D50,
    0x11DA0, 0x11F50, 0x16130, 0x16A60, 0x16AC0, 0x16B50, 0x16D70, 0x1CCF0, 0x1D7CE, 0x1D7D8,
    0x1D7E2, 0x1D7EC, 0x1D7F6, 0x1E140, 0x1E2F0, 0x1E4F0, 0x1E5F1, 0x1E950, 0x1FBF0,
];

/// Decimal value 0-9 of a Unicode Nd digit, or `None` if `c` is not a decimal
/// digit — matching Python `int()` on a single character.
pub fn digit_value(c: char) -> Option<u32> {
    let cp = c as u32;
    if c.is_ascii_digit() {
        return Some(cp - 0x30);
    }
    if cp < 0x80 {
        return None;
    }
    match DIGIT_BLOCK_ZEROS.binary_search(&cp) {
        Ok(_) => Some(0), // c is a block's '0'
        Err(0) => None,   // below the first block
        Err(i) => {
            let zero = DIGIT_BLOCK_ZEROS[i - 1];
            if cp <= zero + 9 {
                Some(cp - zero)
            } else {
                None
            }
        }
    }
}

/// Python `re` `\d`.
#[inline]
pub fn is_digit(c: char) -> bool {
    digit_value(c).is_some()
}

fn in_ranges(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < cp {
                std::cmp::Ordering::Less
            } else if lo > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Python `re` `\w`.
#[inline]
pub fn is_word(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphanumeric() || c == '_';
    }
    in_ranges(PY_WORD, c)
}

/// Python `re` `\s`.
#[inline]
pub fn is_space(c: char) -> bool {
    if c.is_ascii() {
        return matches!(c, '\t'..='\r' | '\x1c'..='\x20');
    }
    in_ranges(PY_SPACE, c)
}

pub(crate) fn char_before(text: &str, i: usize) -> Option<char> {
    text[..i].chars().next_back()
}

pub(crate) fn char_after(text: &str, i: usize) -> Option<char> {
    text[i..].chars().next()
}

// --- shadow text ---------------------------------------------------------------
//
// The regex lane's patterns use ASCII literals and ASCII classes plus `\b`, `\w`,
// `\d` and `\s`. To make Rust's `regex` give Python's answers for the last four,
// it scans a *shadow* of the input in which every character whose Rust and Python
// classes might differ is replaced by a representative with:
//
// * the same UTF-8 length (so every byte offset is unchanged), and
// * the same Python (`\w`, `\d`, `\s`) membership, chosen so that Rust's `\w`,
//   `\d` and `\s` agree on the representative.
//
// No pattern contains a non-ASCII literal or a negated class, so replacing a
// non-ASCII character by another non-ASCII one of the same class cannot change
// any other match decision. `\x1c`-`\x1f` (Python `\s`, not Rust `\s`) become
// `\x0b`, the one ASCII character with the same membership in every class the
// patterns use. Validators and boundary checks always read the ORIGINAL text,
// so digit values and validator inputs are untouched.

// Representatives by (class, UTF-8 length). A Rust unit test pins Rust's own
// classification of every one of them.
const DIGIT_REP: [char; 3] = ['\u{0660}', '\u{0966}', '\u{104A0}']; // Nd
const WORD_REP: [char; 3] = ['\u{00E9}', '\u{6587}', '\u{20000}']; // é 文 𠀀 (letters)
const SPACE_REP: [char; 2] = ['\u{00A0}', '\u{3000}']; // NBSP, ideographic space
const OTHER_REP: [char; 3] = ['\u{00A7}', '\u{2014}', '\u{1F600}']; // § — 😀

fn representative(c: char) -> char {
    let slot = c.len_utf8() - 2; // only non-ASCII characters reach here
    if is_digit(c) {
        DIGIT_REP[slot]
    } else if is_word(c) {
        WORD_REP[slot]
    } else if is_space(c) {
        // every Python whitespace character is below U+10000 (pinned by a test)
        SPACE_REP[slot]
    } else {
        OTHER_REP[slot]
    }
}

/// The text the regex lane scans: the input itself when it is plain ASCII
/// (no copy), otherwise a same-length shadow with Python-faithful classes.
pub(crate) fn shadow(text: &str) -> Cow<'_, str> {
    let needs = text
        .bytes()
        .any(|b| b >= 0x80 || (0x1c..=0x1f).contains(&b));
    if !needs {
        return Cow::Borrowed(text);
    }
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        out.push(match c {
            '\x1c'..='\x1f' => '\x0b',
            c if c.is_ascii() => c,
            c => representative(c),
        });
    }
    debug_assert_eq!(out.len(), text.len());
    Cow::Owned(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use regex::Regex;

    /// Rust's own classes must agree with the intended Python class on every
    /// representative; otherwise the shadow would not do its job.
    #[test]
    fn representatives_have_the_intended_rust_classes() {
        let w = Regex::new(r"\A\w\z").unwrap();
        let d = Regex::new(r"\A\d\z").unwrap();
        let s = Regex::new(r"\A\s\z").unwrap();
        let check = |c: char, word: bool, digit: bool, space: bool| {
            let t = c.to_string();
            assert_eq!(w.is_match(&t), word, "rust \\w on {c:?}");
            assert_eq!(d.is_match(&t), digit, "rust \\d on {c:?}");
            assert_eq!(s.is_match(&t), space, "rust \\s on {c:?}");
            assert_eq!(is_word(c), word, "python \\w on {c:?}");
            assert_eq!(is_digit(c), digit, "python \\d on {c:?}");
            assert_eq!(is_space(c), space, "python \\s on {c:?}");
        };
        for (i, c) in DIGIT_REP.into_iter().enumerate() {
            assert_eq!(c.len_utf8(), i + 2);
            check(c, true, true, false);
        }
        for (i, c) in WORD_REP.into_iter().enumerate() {
            assert_eq!(c.len_utf8(), i + 2);
            check(c, true, false, false);
        }
        for (i, c) in SPACE_REP.into_iter().enumerate() {
            assert_eq!(c.len_utf8(), i + 2);
            check(c, false, false, true);
        }
        for (i, c) in OTHER_REP.into_iter().enumerate() {
            assert_eq!(c.len_utf8(), i + 2);
            check(c, false, false, false);
        }
        check('\x0b', false, false, true);
    }

    #[test]
    fn no_four_byte_python_whitespace() {
        assert!(PY_SPACE.iter().all(|&(_, hi)| hi < 0x10000));
    }

    #[test]
    fn shadow_preserves_byte_offsets() {
        let t = "a²\u{301}文😀\x1c٩ \u{3000}";
        let s = shadow(t);
        assert_eq!(s.len(), t.len());
        for ((i, a), (j, b)) in t.char_indices().zip(s.char_indices()) {
            assert_eq!(i, j);
            assert_eq!(a.len_utf8(), b.len_utf8());
        }
        assert!(matches!(shadow("plain ascii"), Cow::Borrowed(_)));
    }

    #[test]
    fn python_classes_differ_from_rust_where_expected() {
        assert!(is_word('²')); // No: Python \w, not Rust \w
        assert!(!is_word('\u{301}')); // Mn: Rust \w, not Python \w
        assert!(!is_word('‿')); // Pc: Rust \w, not Python \w
        assert!(is_space('\x1c')); // Python \s, not Rust \s
    }
}
