"""Generate native/src/unicode_tables.rs from Python's own ``re`` semantics.

The native core must reproduce Python's ``\\w`` and ``\\s`` character classes
exactly. Python's ``\\w`` is ``str.isalnum() or "_"``, which differs from Rust's
Unicode ``\\w``: Python includes No numerics such as ``²`` and excludes combining
marks and non-``_`` connector punctuation. Python's ``\\s`` is ``str.isspace()``,
which (unlike Unicode White_Space) includes ``\\x1c``-``\\x1f``. The tables are
derived by asking Python's ``re`` engine about every codepoint, so they are the
oracle by construction. (``\\d`` needs no table: it is exactly the Nd blocks of
``DIGIT_BLOCK_ZEROS`` in ``unicode.rs``, which the same test checks codepoint by
codepoint.)

Run with the newest CPython available (its ``unicodedata`` version is recorded in
the generated file); ``tests/test_native_backend.py`` re-checks every codepoint
against the *installed* interpreter.

    python3.14 native/scripts/gen_unicode_tables.py > native/src/unicode_tables.rs
"""

from __future__ import annotations

import re
import sys
import unicodedata


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000 + 1):
        inside = cp <= 0x10FFFF and pred(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return f"{doc}\npub(crate) const {name}: &[(u32, u32)] = &[\n{body}\n];"


def main() -> None:
    word = re.compile(r"\w")
    space = re.compile(r"\s")
    w = ranges(lambda c: word.fullmatch(c) is not None)
    sp = ranges(lambda c: space.fullmatch(c) is not None)
    print("// @generated by native/scripts/gen_unicode_tables.py — do not edit by hand.")
    version = unicodedata.unidata_version
    print(f"// Source: CPython {sys.version.split()[0]} `re`, Unicode {version}.")
    print()
    print(f'pub const UNICODE_VERSION: &str = "{version}";')
    print()
    print(emit("PY_WORD", '/// Python `re` `\\w` (str patterns): `c.isalnum() or c == "_"`.', w))
    print()
    print(emit("PY_SPACE", "/// Python `re` `\\s` (str patterns): `c.isspace()`.", sp))


if __name__ == "__main__":
    main()
